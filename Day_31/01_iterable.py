# Iterable -- An iterable is an object whose items can be accessed one by one.
# Ex -- List,Tuples,String,Dictionari,File,Set

fruits = ["Apple", "Banana", "Mango"]

for fruit in fruits:
    print(fruit)

marks = (98,95,96,92,98,94)

for mark in marks:
    print(mark)

name = "Suraj"

for i in name:
    print(i)

dictn = {101:"Ram",102:"Suraj",103:"Sohan",104:"Rahul"}

for i in dictn:
    print(f"ID: {i}")

