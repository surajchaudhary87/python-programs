# A while loop repeats a block of code as long as the condition is True.

i = 1
while i <= 5:
    print(i)
    i = i+1

#Print 1 to 10 using while loop
n = 1
while n <= 10:
    print(n)
    n = n + 1

#Print 10 to 1 using while loop
num = 10
while num >= 1:
    print(num)
    num = num - 1

#Print Even number using while loop
even = 2
while even <= 20:
    print(even)
    even = even + 2

#Multiplication table using while loop

num = 5
i = 1
while i <= 10:
    print(f"{num} X {i} = {num*i}")
    i = i + 1