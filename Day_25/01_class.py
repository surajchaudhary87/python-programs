# Class -- A class is a blueprint for creating objects.

class Student:
    name = "Suraj"
    age = 20

student1 = Student()    #Here 'Student' is class
print(student1.name)
print(student1.age)


class Car:
    model = "BMW"
    cc = "2000"
    tire = "MRF"
    ac = 8
    airbag = 8

car1 = Car()
print(car1.model)
print(car1.ac)
print(car1.tire)
print(car1.airbag)