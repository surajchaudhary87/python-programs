# Each character in a string has an index number.
# Python indexing start from 0 & Last index size-1 

name = "Python"  # P = 0 || y = 1 || t = 2 || h = 3 || o = 4 || n = 5

print(name[0])
print(name[1])
print(name[2])


# Negative indexing start from -1 = last character

print(name[-1])
print(name[-2])