# Nested loop -- A nested loop means a loop inside another loop

for i in range(1,6):
    for j in range(1,6):
        print(i,j)


# Hello Word 
for i in range(2):
    for i in range(2):
        print("Hello World")  


#Nested loop with numbers
for i in range(1,4):
    for j in range(1,4):
        print(j,end="")     # 123 123 123