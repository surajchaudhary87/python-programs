# Grade finding program

marks = 75

if marks >= 90:
    print("Grade: A")
elif marks >= 80:
    print("Grade: B")
elif marks >= 70:
    print("Grade: C")  # Grade: C
elif marks >= 60:
    print("Grade: D")
elif marks >= 50:
    print("Grade: E")
else:
    print("Grade: F")



# Checking if a number is positive, negative, or zero

num = -5

if num > 0:
    print("The number is positive.")
elif num < 0:
    print("The number is negative.")  # The number is negative.
else :
    print("The number is zero.")



# Checking if a number is even or odd
